#!/usr/bin/env python3
r"""run.py - fpga-ip manifest runner.

Resolves the selected .f manifest for an IP, filters the sources by the tool
profile from tool_capabilities.ini, and dispatches to an EDA backend. Automated
runs write all generated scripts and tool artifacts below <ip>/.runs/<tool>/.

Running the axis_fifo VHDL simulation (ModelSim, GUI) -- two ways:

  1. Via this runner, from the fpga-ip repo root:
       run axis_fifo vhdl modelsim gui

  2. Directly from the IP build directory (script generated by method 1):
    cd axis_fifo/.runs/modelsim
    vsim -do sim_vhdl_msim_default_gui.tcl

Project mode creates a native ModelSim/Questa project (.mpf) in
<ip>/.runs/modelsim/ and opens the GUI:

       run axis_fifo vhdl modelsim project

run.py copies the global %MODELSIM% ini to a writable local modelsim.ini in
the run directory and clears %MODELSIM% before launching vsim, so the .mpf
can be saved (see fpga-rules/questa_modelsim_project_guide.md).

Vivado XSim simulation (Vivado's built-in simulator), batch and GUI, builds
into <ip>/.runs/xsim/. run.py compiles (xvhdl/xvlog) and elaborates (xelab) - XSim
needs one VHDL standard per work library, so all VHDL is compiled at the
manifest DEFAULT_STD - then runs via a generated .tcl (batch) or the GUI:

       run axis_fifo vhdl xsim batch
       run axis_fifo vhdl xsim gui

Vivado synthesis: batch runs non-project synthesis headless in <ip>/.runs/vivado/;
gui loads the design in non-project mode and leaves the Vivado GUI open;
project creates a native .xpr project (design + testbench sources) in
<ip>/.runs/vivado/ and opens the GUI:

       run axis_fifo vhdl vivado batch
       run axis_fifo vhdl vivado gui
       run axis_fifo vhdl vivado project

Remove automated build artifacts for an IP (deletes <ip>/.runs/):
       run clean <ip>

Generated scripts are build artifacts: run.py writes them into the selected
tool directory below <ip>/.runs/ instead of the tracked scripts/ tree, and
'run clean <ip>' removes them along with the build. Use --project-dir for a
persistent user-owned ModelSim or Vivado project; run.py never deletes it.

Architecture overview
---------------------
The flow for a single target is:

  1. Parse the CLI: run <ip> <manifest> <tool> [--tb <tb>] [mode].
  2. Load tool_capabilities.ini (the feature vocabulary + tool profiles).
  3. Load the optional local toolchains.ini and prepare a child environment
      for the requested logical tool/version.
  4. Probe the tool identity (version/edition) in that prepared environment
      and compute its effective feature set.
  5. Resolve <ip>/scripts/<manifest>.f, select the testbench section, and
     build the ordered source closure ([rtl] + [tb], or [rtl] + [top] for
     synthesis).
  6. Validate: sources exist, requires-tokens are legal, capabilities match.
  7. Dispatch to the matching backend (ModelSim/Questa, XSim, or Vivado),
     which writes a generated script into <ip>/.runs/<tool>/ and runs it.
  8. Report PASS/FAIL and map to an exit code.

'run all ...' sweeps every (ip, manifest, tool) combination instead of a
single target, printing an aligned, live PASS/FAIL/SKIP table.

Exit codes
----------
  0   PASS   - every selected target ran cleanly.
  1   FAIL   - compilation, elaboration, synthesis, or simulation failed.
  2   ERROR  - usage, manifest, profile, or validation error.
  3   WARNING - a target ran but a declared capability is missing.

Spec: README.md - "User Manual", ".f Manifest Format (Specification)",
      and "tool_capabilities.ini (Specification)" sections.
"""

