@dataclass
class FileEntry:
    """One resolved source file in the compile closure.

    path is absolute; section is the originating manifest section (for
    reporting); std is the effective VHDL standard (None for non-VHDL or
    unset); lib is the effective library (currently always 'work'); tools
    is the tool= allow-list (empty means all tools); order is the 1-based
    sequence position in the closure, used to preserve compile order.
    """
    path: Path                 # absolute path
    section: str               # originating section (for reporting)
    std: str | None            # effective std (None for non-VHDL / unset)
    lib: str                   # effective library
    tools: list[str]           # allow-list from tool= (empty = all tools)
    order: int                 # sequence number in the closure

    def compile_options(self) -> str:
        opts = []
        if self.std:
            opts.append(f"std={self.std}")
        if self.lib:
            opts.append(f"lib={self.lib}")
        if self.tools:
            opts.append("tool=" + ",".join(self.tools))
        return " ".join(opts) if opts else "-"


@dataclass
class IncludeEntry:
    """A deferred include of one section from another manifest.

    path is the absolute path of the included manifest; section_name is the
    section inside it to import; std_override, when set, forces the VHDL
    standard of every VHDL file expanded from that include; order mirrors
    FileEntry ordering for deterministic in-place expansion.
    """
    path: Path                 # absolute path of included manifest
    section_name: str          # section to import
    std_override: str | None   # include-level std= (None = no override)
    order: int


@dataclass
class Section:
    """One manifest section: metadata (top/requires/...) + ordered entries.

    entries holds FileEntry or IncludeEntry objects in file order. meta
    collects the 'key = value' lines that precede file paths, such as top,
    time_res, requires, wave, and generics.
    """
    name: str
    entries: list = field(default_factory=list)   # FileEntry | IncludeEntry
    meta: dict = field(default_factory=dict)      # top, time_res, requires, wave, generics


@dataclass
class Manifest:
    """A parsed .f manifest: directives, sections, and their file order.

    directives holds the KEY: VALUE globals (DEFAULT_STD/DEFAULT_LIB/
    DEFAULT_TB); sections maps normalized section name -> Section;
    section_order preserves the order sections were declared, which matters
    for testbench enumeration and constraint ordering.
    """
    path: Path
    directives: dict[str, str]
    sections: dict[str, Section]
    section_order: list[str]

    def default_std(self) -> str:
        return self.directives.get("DEFAULT_STD", "2008")

    def default_lib(self) -> str:
        return self.directives.get("DEFAULT_LIB", "work")


def _parse_attrs(tokens: list[str], allowed: set[str]) -> dict[str, str]:
    """Parse 'key=value' tokens into a dict, rejecting unknown keys.

    Called for both file-entry attributes (std/lib/tool) and include-level
    attributes (std only). Rejecting unknown attributes is intentional: a
    typo like 'stt=1993' would otherwise be silently ignored and the file
    compiled at the wrong standard.
    """
    attrs = {}
    for tok in tokens:
        if "=" in tok:
            key, _, value = tok.partition("=")
            key = key.strip().lower()
            if key not in allowed:
                raise RunnerError(f"unknown file attribute '{key}'")
            attrs[key] = value.strip()
    return attrs


def _validate_section_name(name: str) -> None:
    """Reject section names outside the documented vocabulary.

    The runner understands a deliberately small, closed set of sections:
    [rtl], [top], [tb:<name>], [wave:<name>], and [constraints:<tool>]. An
    unnamed [tb] is rejected (must be [tb:<name>]); a typo like [tbb] is a
    hard error rather than a silent no-op, so a mistyped section can never
    quietly change the build.
    """
    if name in RESERVED_SECTIONS:
        return
    if name.startswith("tb:"):
        return
    if name == "tb":
        raise RunnerError("unnamed [tb] section is not supported; use [tb:<name>]")
    if name.startswith("wave:") or name.startswith("constraints:"):
        return
    raise RunnerError(f"unknown section [{name}]")


def _manifest_base(manifest_name: str) -> str:
    """Strip a trailing '.f' from a manifest name ('vhdl.f' -> 'vhdl')."""
    return manifest_name[:-2] if manifest_name.endswith(".f") else manifest_name


def parse_manifest(path: Path) -> Manifest:
    """Parse one .f manifest into a Manifest object.

    The parser is strict by design: unknown sections/directives/attributes
    and duplicate declarations are hard errors, never silent no-ops, so a
    typo cannot quietly change the build. File paths inside the manifest are
    relative to the repository root (not to the manifest's own directory);
    they are resolved to absolute paths here. Only DEFAULT_LIB/lib=work is
    currently supported; any other library is rejected.
    """
    if not path.is_file():
        raise RunnerError(f"manifest not found: {path}")
    directives: dict[str, str] = {}
    sections: dict[str, Section] = {}
    section_order: list[str] = []
    current: Section | None = None

    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue

        if line.startswith("["):
            end = line.find("]")
            if end < 0:
                raise RunnerError(f"malformed section header: {line}")
            name = line[1:end].strip().lower()
            _validate_section_name(name)
            if name in sections:
                raise RunnerError(f"duplicate section [{name}] in {path.name}")
            current = Section(name=name)
            sections[name] = current
            section_order.append(name)
            continue

        if current is None:
            # Global directive: KEY: VALUE
            if ":" not in line:
                raise RunnerError(f"expected directive 'KEY: VALUE' before sections: {line}")
            key, _, value = line.partition(":")
            key = key.strip().upper()
            if key not in VALID_DIRECTIVES:
                raise RunnerError(f"unknown directive '{key}'")
            if key in directives:
                raise RunnerError(f"duplicate directive '{key}'")
            directives[key] = value.strip()
            continue

        # Section metadata line: "key = value" (top, time_res, requires, wave,
        # generics, group, signal, ...). File paths never start with 'identifier ='.
        meta = META_RE.match(line)
        if meta:
            current.meta[meta.group(1).lower()] = meta.group(2).strip()
            continue

        # Section entry: file path with attributes, or an include.
        tokens = line.split()
        if tokens[0].lower() == "include":
            if len(tokens) < 2:
                raise RunnerError(f"include without a path: {line}")
            inc_path = Path(tokens[1])
            section_name = None
            attrs = {}
            for tok in tokens[2:]:
                if tok.startswith("[") and tok.endswith("]"):
                    section_name = tok[1:-1].lower()
                elif "=" in tok:
                    attrs.update(_parse_attrs([tok], {"std"}))
                else:
                    raise RunnerError(f"unexpected include token: {tok}")
            if section_name is None:
                raise RunnerError(f"include missing a [section]: {line}")
            std_override = attrs.get("std")
            if std_override is not None and std_override not in VALID_STDS:
                raise RunnerError(f"invalid include std={std_override} in {path.name}")
            current.entries.append(IncludeEntry(
                path=(REPO_ROOT / inc_path).resolve(),
                section_name=section_name,
                std_override=std_override,
                order=len(current.entries),
            ))
            continue

        attrs = _parse_attrs(tokens[1:], VALID_FILE_ATTRS)
        entry_path = (REPO_ROOT / tokens[0]).resolve()
        std = attrs.get("std")
        if std is not None and std not in VALID_STDS:
            raise RunnerError(f"invalid std={std} for {tokens[0]}")
        lib = attrs.get("lib")
        if lib is not None and lib != "work":
            raise RunnerError(
                f"unsupported lib={lib} for {tokens[0]}; only lib=work is supported"
            )
        tools = [t.strip() for t in attrs.get("tool", "").split(",") if t.strip()]
        current.entries.append(FileEntry(
            path=entry_path,
            section=current.name,
            std=std,
            lib=lib or "",
            tools=tools,
            order=len(current.entries),
        ))

    default_std = directives.get("DEFAULT_STD", "2008")
    if default_std not in VALID_STDS:
        raise RunnerError(f"invalid DEFAULT_STD: {default_std}")
    default_lib = directives.get("DEFAULT_LIB", "work")
    if default_lib != "work":
        raise RunnerError(
            f"unsupported DEFAULT_LIB: {default_lib}; only work is supported"
        )
    if not section_order:
        raise RunnerError(f"manifest has no sections: {path.name}")
    return Manifest(path=path, directives=directives,
                    sections=sections, section_order=section_order)


# ---------------------------------------------------------------------------
# Source closure expansion (includes, ordered, cycle-safe)
# ---------------------------------------------------------------------------

def expand_section(manifest: Manifest, section_name: str,
                   forced_std: str | None, counter: list[int],
                   out: list[FileEntry], stack: list[Path],
                   manifest_cache: dict[Path, Manifest]) -> None:
    """Append resolved FileEntry objects for a section, in order.

    forced_std comes from an include-level std= override and, when set, wins
    over the included manifest's DEFAULT_STD and per-entry std= for VHDL files.
    """
    if section_name not in manifest.sections:
        raise RunnerError(f"section [{section_name}] not found in {manifest.path.name}")
    if manifest.path in stack:
        cycle = " -> ".join(str(p) for p in stack + [manifest.path])
        raise RunnerError(f"include cycle detected: {cycle}")

    stack.append(manifest.path)
    try:
        for entry in manifest.sections[section_name].entries:
            if isinstance(entry, IncludeEntry):
                inc = manifest_cache.get(entry.path)
                if inc is None:
                    inc = parse_manifest(entry.path)
                    manifest_cache[entry.path] = inc
                expand_section(inc, entry.section_name, entry.std_override,
                               counter, out, stack, manifest_cache)
            else:
                is_vhdl = entry.path.suffix.lower() in (".vhd", ".vhdl")
                if forced_std is not None and is_vhdl:
                    std = forced_std
                else:
                    std = entry.std or (manifest.default_std() if is_vhdl else None)
                lib = entry.lib or manifest.default_lib()
                if entry.tools:
                    tools = entry.tools
                else:
                    tools = []
                counter[0] += 1
                out.append(FileEntry(
                    path=entry.path, section=entry.section, std=std, lib=lib,
                    tools=tools, order=counter[0],
                ))
    finally:
        stack.pop()


def build_closure(manifest: Manifest, section_names: list[str],
                  tool: str, manifest_cache: dict[Path, Manifest]) -> list[FileEntry]:
    """Build the ordered source closure for the requested sections.

    Files with a tool= allow-list that excludes the selected tool are skipped.
    Existence of the remaining files is checked by the caller so that the full
    listing can be shown with per-file status.
    """
    out: list[FileEntry] = []
    counter = [0]
    for section in section_names:
        expand_section(manifest, section, None, counter, out, [], manifest_cache)
    # Filter by tool allow-list, preserving order.
    filtered = [e for e in out if not e.tools or tool in e.tools]
    tool_skipped = len(out) - len(filtered)
    # Deduplicate identical sources that were reached through multiple
    # includes. Diamond dependencies are legal (shared RTL pulled in by two
    # testbenches), but the same file must keep the SAME effective
    # attributes everywhere; conflicting std/lib/tool is a hard error rather
    # than a guess, because it would compile the file twice differently.
    unique: list[FileEntry] = []
    seen: dict[Path, FileEntry] = {}
    for entry in filtered:
        previous = seen.get(entry.path)
        if previous is None:
            seen[entry.path] = entry
            unique.append(entry)
            continue
        if (previous.std, previous.lib, previous.tools) != (
                entry.std, entry.lib, entry.tools):
            raise RunnerError(
                f"source included with conflicting attributes: {entry.path}"
            )
    filtered = unique
    if tool_skipped and not _QUIET:
        print(f"  (skipped {tool_skipped} file(s) by tool= allow-list for '{tool}')")
    return filtered


