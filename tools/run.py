def _subprocess_redirect() -> tuple[int | None, int | None]:
    """Redirect targets for tool subprocesses.

    Normal runs inherit the console so the full tool transcript is visible.
    During the 'all' sweep (_QUIET) the output is discarded so each target
    contributes exactly one PASS/FAIL/SKIP line; the tools still write their
    own logs (sim/transcript, xsim/xsim.log, vivado.log), which run.py parses
    for result detection.
    """
    if _QUIET:
        return subprocess.DEVNULL, subprocess.DEVNULL
    return None, None


# The tool subprocess currently running (for Ctrl-C abort); None when idle.
_ACTIVE_PROC: subprocess.Popen | None = None


# Ctrl-C poll granularity. A plain proc.wait() blocks the main thread in a
# Win32 wait that is not interruptible, so polling in short increments lets
# KeyboardInterrupt fire promptly instead of being swallowed by the tool.
_INTERRUPT_POLL_S = 0.2


def _kill_tool(proc: subprocess.Popen) -> None:
    """Force-terminate an EDA tool subprocess and its whole child tree.

    On Windows the child is created in its own process group
    (CREATE_NEW_PROCESS_GROUP), so a CTRL_BREAK_EVENT reaches cmd.exe, the
    .bat wrapper, and the tool itself (it cannot be ignored, unlike a plain
    CTRL_C_EVENT).  CTRL_BREAK only lands when the process group shares a
    real interactive console, so if the tree is still alive after a short
    grace period it is force-killed with `taskkill /F /T` (whole tree),
    falling back to a direct kill of the child. Non-Windows kills the child.
    """
    if proc.poll() is not None:
        return
    if os.name == "nt":
        try:
            os.kill(proc.pid, signal.CTRL_BREAK_EVENT)
        except (OSError, ValueError):
            pass
        try:
            proc.wait(timeout=2)
            return
        except subprocess.TimeoutExpired:
            pass
        # CTRL_BREAK did not land (e.g. non-interactive console); kill the
        # entire tree with taskkill so the tool itself cannot be orphaned.
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)],
                       stdout=subprocess.DEVNULL,
                       stderr=subprocess.DEVNULL)
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass
    try:
        proc.kill()
    except OSError:
        pass


def _wait_tool(proc: subprocess.Popen) -> int:
    """Wait for a tool subprocess with Ctrl-C kept responsive.

    A plain proc.wait() blocks the main thread in a Win32 wait that is not
    interruptible by Ctrl-C (the signal is only delivered once the child
    exits). Polling in short increments lets KeyboardInterrupt fire promptly
    instead; on interrupt the whole child tree is force-killed before the
    exception is re-raised so the run/sweep aborts.
    """
    global _ACTIVE_PROC
    _ACTIVE_PROC = proc
    try:
        while True:
            try:
                return proc.wait(timeout=_INTERRUPT_POLL_S)
            except subprocess.TimeoutExpired:
                continue
    except KeyboardInterrupt:
        _kill_tool(proc)
        raise
    finally:
        _ACTIVE_PROC = None


def _tee_tool(proc: subprocess.Popen, log_file) -> int:
    """Copy a tool's combined stdout+stderr to log_file and the console.

    The pipe is drained on a daemon thread so the main thread can poll the
    process with short timeouts, keeping Ctrl-C responsive during verbose
    (non-sweep) runs that capture output.
    """
    assert proc.stdout is not None
    chunks: queue.Queue = queue.Queue()

    def _reader() -> None:
        try:
            for chunk in iter(lambda: proc.stdout.read(65536), b""):
                chunks.put(chunk)
        finally:
            chunks.put(None)

    threading.Thread(target=_reader, daemon=True).start()
    global _ACTIVE_PROC
    _ACTIVE_PROC = proc
    try:
        eof = False
        rc: int | None = None
        while not eof:
            try:
                rc = proc.wait(timeout=_INTERRUPT_POLL_S)
            except subprocess.TimeoutExpired:
                rc = None
            while True:
                try:
                    chunk = chunks.get_nowait()
                except queue.Empty:
                    break
                if chunk is None:
                    eof = True
                    break
                log_file.write(chunk)
                sys.stdout.buffer.write(chunk)
                sys.stdout.buffer.flush()
        if rc is None:
            rc = proc.wait()
        # Drain anything still queued ahead of the sentinel.
        while True:
            try:
                chunk = chunks.get_nowait()
            except queue.Empty:
                break
            if chunk is None:
                break
            log_file.write(chunk)
            sys.stdout.buffer.write(chunk)
            sys.stdout.buffer.flush()
        return rc
    except KeyboardInterrupt:
        _kill_tool(proc)
        raise
    finally:
        _ACTIVE_PROC = None


def _run_cmd(cmd: str, cwd: Path | None = None, env: dict | None = None,
             log_path: Path | None = None) -> int:
    """Run one EDA command through the platform shell and return its exit code.

    Windows uses `cmd.exe /c <cmd>` because the EDA tools are .bat wrappers
    that replace the calling process when invoked directly. POSIX uses
    `sh -c <cmd>`. This helper centralizes console redirection and the
    optional working directory/environment for each backend.

    cwd, when given, is the process working directory (used by XSim and
    Vivado, which keep their artifacts in a build dir). env, when given,
    overrides the child environment (used by ModelSim project mode to clear
    %MODELSIM%).
    """
    # Windows: isolate the child in its own process group so a Ctrl-C abort
    # can terminate the whole tree (cmd.exe + .bat wrapper + tool) instead
    # of the tool swallowing the keystroke.
    creationflags = 0
    if os.name == "nt":
        command = ["cmd.exe", "/c", cmd]
        command_label = f"cmd.exe /c \"{cmd}\""
    else:
        command = ["sh", "-c", cmd]
        command_label = f"sh -c \"{cmd}\""
    if os.name == "nt":
        creationflags = getattr(subprocess, "CREATE_NEW_PROCESS_GROUP", 0)

    if not _QUIET:
        cwd_note = f" (cwd: {cwd})" if cwd is not None else ""
        print(f"cmd : {command_label}{cwd_note}")

    def _launch(stdout, stderr) -> subprocess.Popen:
        return subprocess.Popen(command, cwd=cwd, env=env,
                                stdout=stdout, stderr=stderr,
                                creationflags=creationflags)

    if log_path is not None:
        log_path.parent.mkdir(parents=True, exist_ok=True)
        if _QUIET:
            with log_path.open("wb") as lf:
                return _wait_tool(_launch(lf, subprocess.STDOUT))
        # Not quiet: tee the child output to the log file and the console
        # so the user still sees the tool output live while a capture exists
        # for failure detection and archiving.
        with log_path.open("wb") as lf:
            return _tee_tool(_launch(subprocess.PIPE, subprocess.STDOUT), lf)
    out, err = _subprocess_redirect()
    return _wait_tool(_launch(out, err))


_LAST_FAILURE_ARTIFACT: Path | None = None


def run_msim(launch_dir: Path, script_name: str, mode: str,
             tool_env: dict[str, str] | None = None) -> int:
    """Invoke ModelSim/Questa (vsim) directly in a CMD shell.

    vsim must already be on the PATH.
    launch_dir is the selected run directory. GUI mode runs
    `vsim -do <script>` (no -c): the GUI opens and
    this call blocks until the user closes it. Avoid `start /B`, whose
    empty title is mangled by the nested quoting inside `cmd /c "..."`.

    Project mode additionally copies the global %MODELSIM% ini to a writable
    local modelsim.ini in the run directory and clears %MODELSIM% for the
    child process. ModelSim/Questa cannot save the .mpf when %MODELSIM%
    points at a shared/read-only ini ("Unable to replace existing ini file
    ... Access is denied"). See fpga-rules/questa_modelsim_project_guide.md.
    """
    global _LAST_FAILURE_ARTIFACT
    _LAST_FAILURE_ARTIFACT = None
    if mode == "batch":
        vsim_cmd = f"vsim -c -do {script_name}"
    else:
        vsim_cmd = f"vsim -do {script_name}"
    env = dict(tool_env) if tool_env is not None else None
    if mode == "project":
        sim_dir = launch_dir.resolve()
        sim_dir.mkdir(parents=True, exist_ok=True)
        setup_env = env or os.environ
        global_ini = setup_env.get("MODELSIM") or setup_env.get("QSIM_INI")
        if global_ini and os.path.isfile(global_ini):
            local_ini = sim_dir / "modelsim.ini"
            shutil.copyfile(global_ini, local_ini)
            try:
                os.chmod(local_ini, 0o644)  # clear any read-only attribute
            except OSError:
                pass
        env = dict(setup_env)
        env.pop("MODELSIM", None)
        env.pop("QSIM_INI", None)
    inner = f"cd /d {launch_dir} & {vsim_cmd}"
    # vsim inherits the console unless the sweep suppressed output; cwd is
    # set via 'cd /d' inside the CMD string (vsim must start in the run dir).
    rc = _run_cmd(inner, env=env, log_path=launch_dir / "tool_output.log")
    transcript_failed = False
    if mode == "batch" and rc == 0:
        # vsim -c exits 0 even when a VHDL assertion fails at runtime
        # (onerror only catches Tcl errors); scan the transcript instead.
        sim_dir = launch_dir.resolve()
        transcript_failed = _msim_transcript_failed(sim_dir)
        if transcript_failed:
            rc = 1
    if mode == "batch" and (rc != 0 or _diagnostics_enabled()):
        _LAST_FAILURE_ARTIFACT = _archive_msim_run(
            launch_dir, script_name, rc, transcript_failed, tool_env
        )
        if not _QUIET:
            label = "diagnostics" if rc == 0 else "failure diagnostics"
            print(f"{label}: {_LAST_FAILURE_ARTIFACT}", file=sys.stderr)
    return rc


