def build_arg_parser() -> argparse.ArgumentParser:
    """Construct the argparse CLI parser.

    Positionals are <ip> <manifest> <tool> [mode]; mode defaults to 'batch'.
    'all' is accepted for ip/manifest/tool to trigger the sweep, and the
    'clean' subcommand is handled separately in main() before this parser.
    Options: --tb (testbench selection), --part (Vivado part), --version /
    --edition (tool identity overrides), --project-dir (persistent project).
    """
    p = argparse.ArgumentParser(
        prog="run",
        description="fpga-ip manifest runner",
        epilog=(
            "examples:\n"
            "  run axis_fifo vhdl modelsim gui\n"
            "  run axis_fifo vhdl modelsim project\n"
            "  run axis_fifo vhdl modelsim --tb default\n"
            "  run axis_fifo vhdl xsim batch\n"
            "  run axis_fifo vhdl xsim gui\n"
            "  run axis_fifo vhdl vivado batch\n"
            "  run axis_fifo vhdl vivado gui\n"
            "  run axis_fifo vhdl vivado project\n"
            "  run axis_fifo vhdl modelsim project --project-dir proj/modelsim\n"
            "  run axis_fifo vhdl vivado project --project-dir proj/vivado\n"
            "  run all all all           # every IP/manifest/tool, batch\n"
            "  run all vhdl modelsim     # every IP, vhdl.f, ModelSim\n"
            "  run clean axis_fifo"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("ip", help="IP directory under the repo root, or 'all'")
    p.add_argument("manifest", help="manifest name (vhdl or vhdl.f), or 'all'")
    p.add_argument("tool", help="tool profile name (modelsim, questa, vivado, xsim), or 'all'")
    p.add_argument("--tb", dest="tb", default=None,
                   help="testbench name, or 'all'")
    p.add_argument("--part", default=None,
                   help=f"Vivado target part (default: {VIVADO_DEFAULT_PART})")
    p.add_argument("--version", default=None, help="optional tool version override")
    p.add_argument("--edition", default=None, help="optional tool edition override")
    p.add_argument("--project-dir", default=None,
                   help="persistent project directory (relative to the IP) for project mode; never cleaned")
    p.add_argument("mode", nargs="?", default="batch",
                   help="batch (default), gui, or project ('all' is batch-only)")
    return p


def main(argv: list[str] | None = None) -> int:
    """Entry point for one command-line invocation.

    Flow: parse args -> load capabilities -> (sweep or single target) ->
    select testbench -> build closure -> validate -> dispatch to the backend
    -> map result to an exit code. Each step validates its input and returns
    2 (usage/validation error) with a clear message on failure, so errors
    are reported consistently regardless of which backend would have run.
    Returns 0 on success, nonzero on any failure (see module docstring).
    """
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] == "clean":
        return cmd_clean(argv[1:])
    args = build_arg_parser().parse_args(argv)

    mode = args.mode
    if mode not in VALID_MODES:
        print(f"ERROR: unknown mode '{mode}' (expected {', '.join(VALID_MODES)})", file=sys.stderr)
        return 2
    if args.project_dir and mode != "project":
        print("ERROR: --project-dir is only valid with project mode", file=sys.stderr)
        return 2

    try:
        caps = Capabilities.load(INI_PATH)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    toolchains = Toolchains.load()

    # 'all' sweep: every ip/manifest/tool combination, batch only.
    if args.ip == "all" or args.manifest == "all" or args.tool == "all":
        if mode != "batch":
            print(f"ERROR: 'all' targets only run in batch mode (got '{mode}')",
                  file=sys.stderr)
            return 2
        return _run_all(args, caps, toolchains)

    tool = args.tool
    if not caps.has_tool(tool):
        print(f"ERROR: unsupported tool '{tool}' (no profile in tool_capabilities.ini)",
              file=sys.stderr)
        return 2
    modes = caps.profile_modes(tool)
    if modes and mode not in modes:
        print(f"ERROR: mode '{mode}' not supported by '{tool}' (modes: {', '.join(modes)})",
              file=sys.stderr)
        return 2
    if args.project_dir and tool not in MSIM_TOOLS + ("vivado",):
        print(f"ERROR: --project-dir is not supported by '{tool}'", file=sys.stderr)
        return 2

    manifest_name = args.manifest if args.manifest.endswith(".f") else args.manifest + ".f"
    manifest_path = (REPO_ROOT / args.ip / "scripts" / manifest_name).resolve()
    try:
        manifest_path.relative_to(REPO_ROOT)
    except ValueError:
        print(f"ERROR: manifest path escapes repo root: {manifest_path}", file=sys.stderr)
        return 2

    try:
        manifest = parse_manifest(manifest_path)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    try:
        tb_names = select_testbenches(manifest, args.tb, tool)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    try:
        tool_env = toolchains.prepare(tool, args.version)
        detected_version, detected_edition = caps.detect_identity(tool, tool_env)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2
    if args.version and detected_version and detected_version != args.version:
        print(f"ERROR: requested {tool} {args.version}, but setup produced "
              f"{tool} {detected_version}", file=sys.stderr)
        return 2
    if args.edition and detected_edition and detected_edition != args.edition.lower():
        print(f"ERROR: requested {tool} edition {args.edition}, but setup produced "
              f"edition {detected_edition}", file=sys.stderr)
        return 2
    provided = caps.effective_features_for(
        tool, args.version, args.edition, tool_env
    )
    if not _QUIET:
        setup_name = toolchains.setup_command(tool, args.version)
        detected_label = detected_version or "unknown version"
        if detected_edition:
            detected_label += f" / {detected_edition}"
        print(f"toolchain: {setup_name or '(current environment)'}")
        print(f"detected  : {tool} {detected_label}")
    manifest_cache: dict[Path, Manifest] = {manifest.path: manifest}

    exit_code = 0
    for tb_name in tb_names or [None]:
        tb_label = tb_name.removeprefix("tb:") if tb_name else "synthesis"
        sections = target_sections(manifest, tb_name)
        try:
            files = build_closure(manifest, sections, tool, manifest_cache)
        except RunnerError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2

        # Header / file listing (verbose only; the 'all' sweep prints one line).
        if not _QUIET:
            print(f"target   : {args.ip} / {manifest_name} / {tool} / {tb_label} / {mode}")
            if tb_name:
                meta = manifest.sections[tb_name].meta
                req_names = [n for _, n in parse_feature_tokens(meta.get("requires", ""))]
                print(f"top      : {meta.get('top', '(missing)')}")
                print(f"requires : {', '.join(req_names) if req_names else '(none)'}")
            print("files (compile order):")
            for entry in files:
                rel = entry.path.relative_to(REPO_ROOT).as_posix()
                opts = entry.compile_options()
                if entry.path.is_file():
                    print(f"  [OK   ] [{entry.section:12}] {opts:24} {GREEN}{rel}{RESET}")
                else:
                    print(f"  [MISS ] [{entry.section:12}] {opts:24} {RED}{rel}{RESET}")
            print()
            ok_n = sum(1 for e in files if e.path.is_file())
            miss_n = len(files) - ok_n
            if miss_n:
                print(f"  summary: {GREEN}{ok_n} found{RESET}, "
                       f"{RED}{miss_n} missing{RESET}")
            else:
                print(f"  summary: {GREEN}{len(files)} files found{RESET}")
        # Validation that applies in every mode (also during the sweep):
        if tb_name:
            bad = [n for _, n in parse_feature_tokens(
                manifest.sections[tb_name].meta.get("requires", ""))
                if n not in caps.allowed]
            if bad:
                if not _QUIET:
                    print(f"ERROR: requires token(s) not in allowed_features: "
                          f"{', '.join(bad)}", file=sys.stderr)
                return 2
        missing_paths = [e.path for e in files if not e.path.is_file()]
        if missing_paths:
            if not _QUIET:
                for p in missing_paths:
                    print(f"{RED}ERROR: source file not found: {p}{RESET}",
                          file=sys.stderr)
            return 2

        if tb_name:
            meta = manifest.sections[tb_name].meta
            req_names = [n for _, n in parse_feature_tokens(meta.get("requires", ""))]
            missing = [n for n in req_names if n not in provided]
            if missing:
                if not _QUIET:
                    print(f"  WARNING: missing capability(ies) for '{tool}': "
                          f"{', '.join(missing)}")
                exit_code = 3

        # ModelSim / Questa simulation backend (non-project mode).
        if tb_name is not None and tool in MSIM_TOOLS:
            top = manifest.sections[tb_name].meta.get("top")
            if not top:
                if not _QUIET:
                    print(f"ERROR: testbench [{tb_name}] has no 'top' metadata",
                          file=sys.stderr)
                return 2
            time_res = manifest.sections[tb_name].meta.get("time_res")
            manifest_base = _manifest_base(manifest_name)
            # Filename segments follow the command-line order:
            #   run <ip> <manifest> <tool> [--tb <tb>] [mode]
            # -> sim_<manifest>_<tool>_<tb>_<mode>.tcl  (synthesis omits tb).
            # Shorten common tool names in the filename (modelsim -> msim).
            tool_tag = {"modelsim": "msim"}.get(tool, tool)
            if tb_name:
                script_name = f"sim_{manifest_base}_{tool_tag}_{tb_label}_{mode}.tcl"
            else:
                script_name = f"sim_{manifest_base}_{tool_tag}_{mode}.tcl"
            # Automated runs are disposable. An explicit project directory is
            # user-owned and must be new/empty; it is never cleaned by run.py.
            if mode == "project" and args.project_dir:
                try:
                    build_dir = _persistent_project_dir(args.project_dir, args.ip)
                except RunnerError as exc:
                    print(f"ERROR: {exc}", file=sys.stderr)
                    return 2
            else:
                build_dir = _auto_run_dir(args.ip, tool)
                _prepare_auto_run_dir(build_dir)
            script_path = build_dir / script_name
            write_msim_script(script_path, files, top, time_res, mode, tool,
                              manifest_base, args.ip, tb_label, script_name,
                              generics=meta.get("generics"))
            if not _QUIET:
                print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            # The generated script rebuilds the work library itself. Use
            # 'run clean <ip>' to remove disposable .runs artifacts.
            rc = run_msim(script_path.parent, script_name, mode, tool_env)
            exit_code = report_sim_result(mode, rc) or exit_code
        # Vivado XSim simulation backend (batch/gui; no project mode).
        elif tb_name is not None and tool == "xsim":
            # XSim ships no UVVM libraries; skip testbenches whose requires
            # the xsim profile does not provide (mirrors simulate_xsim.bat).
            meta = manifest.sections[tb_name].meta
            req_names = [n for _, n in parse_feature_tokens(meta.get("requires", ""))]
            missing = [n for n in req_names if n not in provided]
            if missing:
                if not _QUIET:
                    print(f"  SKIP: testbench [{tb_name}] requires capabilities not "
                          f"provided by 'xsim': {', '.join(missing)}")
                continue
            top = meta.get("top")
            if not top:
                if not _QUIET:
                    print(f"ERROR: testbench [{tb_name}] has no 'top' metadata",
                          file=sys.stderr)
                return 2
            manifest_base = _manifest_base(manifest_name)
            script_name = f"sim_{manifest_base}_{tool}_{tb_label}_{mode}.tcl"
            # XSim runs are disposable and always use the single xsim folder.
            build_dir = _auto_run_dir(args.ip, tool)
            _prepare_auto_run_dir(build_dir)
            script_path = build_dir / script_name
            # XSim requires one VHDL standard per work library, so all VHDL
            # is compiled at the manifest default; flag mixed-std manifests.
            std = manifest.default_std()
            vhdl_stds = {e.std or std for e in files
                         if e.path.suffix.lower() in (".vhd", ".vhdl")}
            if len(vhdl_stds) > 1 and not _QUIET:
                print(f"  NOTE: XSim compiles all VHDL at DEFAULT_STD {std} "
                      f"(one standard per work library; per-file std ignored)")
            write_xsim_script(script_path, files, top, mode, tool,
                              manifest_base, args.ip, tb_label, script_name, std,
                              generics=meta.get("generics"))
            if not _QUIET:
                print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            rc = run_xsim(script_path.parent, script_path, mode, tool_env)
            exit_code = report_sim_result(mode, rc) or exit_code
        # Vivado synthesis backend (batch/gui/project).
        elif tool == "vivado":
            if "top" not in manifest.sections:
                if not _QUIET:
                    print("ERROR: manifest has no [top] section; synthesis requires "
                          "a top-level wrapper", file=sys.stderr)
                return 2
            top = _top_entity(manifest, files)
            if not top:
                if not _QUIET:
                    print("ERROR: cannot determine the top entity from the [top] "
                          "section", file=sys.stderr)
                return 2
            part = args.part or VIVADO_DEFAULT_PART
            manifest_base = _manifest_base(manifest_name)
            script_name = f"synth_{manifest_base}_{tool}_{mode}.tcl"
            if mode in ("batch", "gui"):
                # Non-project: batch runs headless, gui loads the design and
                # leaves the Vivado GUI open. No project, no testbenches.
                build_dir = _auto_run_dir(args.ip, tool)
                proj_dir = None
            else:
                # project: native .xpr with testbench sources in sim_1, then GUI.
                if args.project_dir:
                    try:
                        build_dir = _persistent_project_dir(args.project_dir, args.ip)
                    except RunnerError as exc:
                        print(f"ERROR: {exc}", file=sys.stderr)
                        return 2
                else:
                    build_dir = _auto_run_dir(args.ip, tool)
                    _prepare_auto_run_dir(build_dir)
                proj_dir = build_dir / f"{top}_proj"
            # Reset the build dir, then write the generated script into it:
            # scripts are build artifacts, not part of the tracked scripts/ tree.
            if mode != "project" or not args.project_dir:
                _prepare_auto_run_dir(build_dir)
            script_path = build_dir / script_name
            if mode in ("batch", "gui"):
                if mode == "batch":
                    write_vivado_synth_script(script_path, files, top, part, tool,
                                              manifest_base, args.ip, script_name)
                else:
                    write_vivado_gui_script(script_path, files, top, part, tool,
                                            manifest_base, args.ip, script_name)
            else:
                tb_sections = [n for n in manifest.section_order if n.startswith("tb:")]
                sim_files: list[FileEntry] = []
                if tb_sections:
                    try:
                        sim_files = [e for e in
                                     build_closure(manifest, tb_sections, tool, manifest_cache)
                                     if e.path.is_file()]
                    except RunnerError as exc:
                        if not _QUIET:
                            print(f"ERROR: {exc}", file=sys.stderr)
                        return 2
                write_vivado_project_script(script_path, files, sim_files, top,
                                            part, mode, tool, manifest_base,
                                            args.ip, script_name)
            if not _QUIET:
                print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            rc = run_vivado(build_dir, script_path, mode, proj_dir, tool_env)
            exit_code = report_sim_result(mode, rc) or exit_code

    return exit_code


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nAborted by user (Ctrl-C).", file=sys.stderr)
        sys.exit(130)
