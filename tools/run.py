def _auto_run_dir(ip: str, tool: str) -> Path:
    """Return the stable per-IP, per-tool run directory.

    ModelSim and Questa share one folder (both drive 'vsim'), so they map
    to the same 'modelsim' subdirectory under <ip>/.runs/. Other tools use
    their own name. Each invocation replaces the previous generated script
    and tool artifacts in that directory.
    """
    tool_dir = "modelsim" if tool in ("modelsim", "questa") else tool
    return REPO_ROOT / ip / RUNS_DIRNAME / tool_dir


def _persistent_project_dir(value: str, ip: str) -> Path:
    """Resolve a user-owned project directory.

    Relative paths resolve against the IP directory, so 'proj/sim01' means
    <ip>/proj/sim01 - the mirror of the <ip>/.runs layout, giving each IP its
    own projects. Absolute paths are used as given. Either way the result must
    stay below the fpga-ip root and outside .runs.
    """
    path = Path(value)
    if path.is_absolute():
        path = path.resolve()
    else:
        path = (REPO_ROOT / ip / path).resolve()
    try:
        path.relative_to(REPO_ROOT)
    except ValueError as exc:
        raise RunnerError("--project-dir must be below the fpga-ip root") from exc
    if RUNS_DIRNAME in path.relative_to(REPO_ROOT).parts:
        raise RunnerError("--project-dir must not be below .runs")
    if path.exists() and any(path.iterdir()):
        raise RunnerError(f"project directory is not empty; refusing to overwrite: {path}")
    path.mkdir(parents=True, exist_ok=True)
    return path


def _diagnostics_enabled() -> bool:
    """Return whether hidden per-run diagnostic archives are enabled."""
    value = os.environ.get(DIAGNOSTICS_ENV, "").strip().lower()
    return value not in ("", "0", "false", "no", "off")


def _prepare_auto_run_dir(path: Path) -> None:
    """Recreate one clean automated tool-run directory.

    The caller supplies a stable path under <ip>/.runs/ (see _auto_run_dir),
    so each run replaces stale libraries, transcripts, snapshots, and the
    generated script from the previous run without touching tracked sources.
    """
    cleanup_errors: list[str] = []

    def record_cleanup_error(function, failed_path, exc_info) -> None:
        cleanup_errors.append(
            f"{function.__name__} {failed_path}: {exc_info[1]}"
        )

    shutil.rmtree(path, onerror=record_cleanup_error)
    if cleanup_errors:
        diagnostics_dir = path.parent / "diagnostics"
        diagnostics_dir.mkdir(parents=True, exist_ok=True)
        with (diagnostics_dir / "cleanup.log").open("a", encoding="utf-8") as log:
            log.write(f"run_dir = {path.resolve()}\n")
            log.write("\n".join(cleanup_errors) + "\n\n")
    path.mkdir(parents=True, exist_ok=True)

