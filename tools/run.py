# 'all' sweep (run <ip|all> <manifest|all> <tool|all>, batch only)
# ---------------------------------------------------------------------------

# While set, the per-target output (target/files/script/cmd/result and error
# messages) is suppressed so the sweep can print one line per target ending
# in PASS/FAIL/SKIP. main() is re-invoked per combination under this flag.
_QUIET = False

# Map a VHDL standard (manifest values 1993/2002/2008/2019) to its
# tool-capability feature token.
_STD_FEATURE = {"1993": "vhdl-93", "2002": "vhdl-2002",
                "2008": "vhdl-2008", "2019": "vhdl-2019"}


def _all_ips() -> list[str]:
    """Names of every IP directory that has at least one .f manifest.

    Drives the 'run all ...' sweep: each directory directly under the repo
    root that has a scripts/ subdirectory containing at least one *.f file
    is treated as an IP. Dot-directories (like .runs or .git) are skipped.
    """
    out = []
    for p in sorted(REPO_ROOT.iterdir()):
        if not p.is_dir() or p.name.startswith("."):
            continue
        scripts = p / "scripts"
        if scripts.is_dir() and any(scripts.glob("*.f")):
            out.append(p.name)
    return out


def _all_manifests(ip: str) -> list[str]:
    """Manifest base names (without .f) for an IP, in sorted order.

    Sorted so the sweep output is stable and deterministic across runs.
    """
    return sorted(p.stem for p in (REPO_ROOT / ip / "scripts").glob("*.f"))


def _skip_reason(caps: Capabilities, manifest: Manifest, tool: str,
                 provided: set[str]) -> str | None:
    """Return why (manifest, tool) cannot run in a sweep, or None to run."""
    # VHDL standard support (the manifest default plus per-file overrides).
    stds = {manifest.default_std()}
    for section in manifest.sections.values():
        for entry in section.entries:
            if (isinstance(entry, FileEntry) and entry.std
                    and entry.path.suffix.lower() in (".vhd", ".vhdl")):
                stds.add(entry.std)
    missing_std = sorted(_STD_FEATURE[s] for s in stds
                         if _STD_FEATURE.get(s) not in provided)
    if missing_std:
        return f"requires {', '.join(missing_std)} not provided by {tool}"
    # Declared feature requirements from the testbench sections.
    reqs = set()
    for section in manifest.sections.values():
        for _, name in parse_feature_tokens(section.meta.get("requires", "")):
            reqs.add(name)
    missing_req = sorted(r for r in reqs if r not in provided)
    if missing_req:
        return f"requires {', '.join(missing_req)} not provided by {tool}"
    # Vivado synthesis needs a [top] section.
    if tool == "vivado" and "top" not in manifest.sections:
        return "no [top] section; synthesis requires a top wrapper"
    return None


def _run_all(args, caps: Capabilities, toolchains: Toolchains) -> int:
    """Run every (ip, manifest, tool) combination in batch mode.

    Prints each target's row immediately as it starts (progress) with its
    IP / MANIFEST / TB / TOOL in separate aligned columns, then appends a
    colored PASS/FAIL/SKIP in the RESULT column (SKIP with a reason), then a
    summary. Returns nonzero if any target FAILed. Each non-skipped target
    is executed by re-invoking main() with quiet output, so the exact
    single-target backend behavior is reused.

    The sweep always continues past a FAIL so every (ip, manifest, tool)
    combination is exercised and reported. Failure diagnostics are archived
    per target when FPGA_IP_DIAGNOSTICS is enabled (see _archive_*_run);
    they do not stop the sweep.
    """
    global _QUIET, _LAST_FAILURE_ARTIFACT
    ips = _all_ips() if args.ip == "all" else [args.ip]
    tools = caps.tool_names() if args.tool == "all" else [args.tool]
    manifests = {ip: (_all_manifests(ip) if args.manifest == "all"
                      else [args.manifest]) for ip in ips}

    # A typo'd IP or an IP with no .f manifests would otherwise silently
    # produce an empty sweep ("0 passed, 0 failed, 0 skipped"); fail loudly.
    if args.ip != "all" and not (REPO_ROOT / args.ip).is_dir():
        print(f"ERROR: IP directory not found: {args.ip}", file=sys.stderr)
        return 2
    for ip, ml in manifests.items():
        if not ml:
            print(f"ERROR: no .f manifests under {ip}/scripts", file=sys.stderr)
            return 2

    # Resolve each target's columns (ip, manifest, tb, tool) up front - the
    # tb is the one main() runs (the manifest's default) - so the per-column
    # widths can be computed and every field lines up in its own column.
    cols: dict[tuple[str, str, str], tuple[str, str, str, str]] = {}
    for ip in ips:
        for manifest in manifests[ip]:
            for tool in tools:
                tb = ""
                if caps.has_tool(tool):
                    try:
                        mo = parse_manifest(
                            (REPO_ROOT / ip / "scripts" / f"{manifest}.f").resolve())
                        tbs = select_testbenches(mo, None, tool)
                        if len(tbs) == 1:
                            tb = tbs[0].removeprefix("tb:")
                    except RunnerError:
                        pass  # the run loop reports manifest errors itself
                cols[(ip, manifest, tool)] = (ip, manifest, tb, tool)
    w_ip = max(len("IP"), max((len(c[0]) for c in cols.values()), default=0))
    w_man = max(len("MANIFEST"), max((len(c[1]) for c in cols.values()), default=0))
    w_tb = max(len("TB"), max((len(c[2]) for c in cols.values()), default=0))
    w_tool = max(len("TOOL"), max((len(c[3]) for c in cols.values()), default=0))
    # Column header so the fields are self-explanatory.
    print(f"{'IP':<{w_ip}}  {'MANIFEST':<{w_man}}  {'TB':<{w_tb}}  "
          f"{'TOOL':<{w_tool}}  RESULT")

    def row(ip_c: str, man_c: str, tb_c: str, tool_c: str) -> str:
        return (f"{ip_c:<{w_ip}}  {man_c:<{w_man}}  {tb_c:<{w_tb}}  "
                f"{tool_c:<{w_tool}}  ")

    passed = failed = skipped = 0
    failed_list: list[tuple[str, str]] = []
    skipped_list: list[tuple[str, str]] = []
    for ip in ips:
        for manifest in manifests[ip]:
            for tool in tools:
                ip_c, man_c, tb_c, tool_c = cols[(ip, manifest, tool)]
                # Compact identifier for the summary lists (no slashes).
                ident = " ".join(x for x in (ip_c, man_c, tb_c, tool_c) if x)
                if not caps.has_tool(tool):
                    skipped += 1
                    skipped_list.append((ident, "unknown tool"))
                    print(f"{row(ip_c, man_c, tb_c, tool_c)}"
                          f"{YELLOW}SKIP{RESET} (unknown tool)")
                    continue
                mpath = (REPO_ROOT / ip / "scripts" / f"{manifest}.f").resolve()
                try:
                    manifest_obj = parse_manifest(mpath)
                except RunnerError as exc:
                    failed += 1
                    failed_list.append((ident, str(exc)))
                    print(f"{row(ip_c, man_c, tb_c, tool_c)}"
                          f"{RED}FAIL{RESET} ({exc})")
                    continue
                try:
                    tool_env = toolchains.prepare(tool, args.version)
                    provided = caps.effective_features_for(
                        tool, args.version, args.edition, tool_env
                    )
                except RunnerError as exc:
                    skipped += 1
                    skipped_list.append((ident, str(exc)))
                    print(f"{row(ip_c, man_c, tb_c, tool_c)}"
                          f"{YELLOW}SKIP{RESET} ({exc})")
                    continue
                reason = _skip_reason(caps, manifest_obj, tool, provided)
                if reason:
                    skipped += 1
                    skipped_list.append((ident, reason))
                    print(f"{row(ip_c, man_c, tb_c, tool_c)}"
                          f"{YELLOW}SKIP{RESET} ({reason})")
                    continue
                # Running target: print its row immediately (no newline) so
                # the user sees what is executing, then append the result.
                print(row(ip_c, man_c, tb_c, tool_c), end="", flush=True)
                _QUIET = True
                _LAST_FAILURE_ARTIFACT = None
                try:
                    child_args = [ip, manifest, tool]
                    if args.version:
                        child_args += ["--version", args.version]
                    if args.edition:
                        child_args += ["--edition", args.edition]
                    child_args.append("batch")
                    rc = main(child_args)
                finally:
                    _QUIET = False
                if rc == 0:
                    passed += 1
                    print(f"{GREEN}PASS{RESET}")
                else:
                    failed += 1
                    failure_note = f"exit {rc}"
                    if _LAST_FAILURE_ARTIFACT is not None:
                        try:
                            artifact = _LAST_FAILURE_ARTIFACT.relative_to(REPO_ROOT)
                        except ValueError:
                            artifact = _LAST_FAILURE_ARTIFACT
                        failure_note += f"; diagnostics: {artifact.as_posix()}"
                    failed_list.append((ident, failure_note))
                    print(f"{RED}FAIL{RESET} ({failure_note})")

    print()
    print("=" * 62)
    total = passed + failed + skipped
    print(f"Summary: {passed} passed, {failed} failed, {skipped} skipped"
          f" ({total} total)")
    if failed_list:
        print("FAILED:")
        for label, r in failed_list:
            print(f"  {label}: {r}")
    if skipped_list:
        print("SKIPPED:")
        for label, r in skipped_list:
            print(f"  {label}: {r}")
    return 1 if failed else 0


