def select_testbenches(manifest: Manifest, tb_arg: str | None,
                       tool: str) -> list[str]:
    """Return the list of [tb:<name>] sections to run for this target.

    Resolution order:
      1. --tb <name>  -> exactly [tb:<name>]
      2. --tb all     -> every testbench section in the manifest
      3. no --tb and DEFAULT_TB set -> that named testbench
      4. no --tb and exactly one testbench -> the only one (implicit)
      5. no --tb and multiple, no default -> error; the user must pick

    Vivado synthesis never accepts --tb and never runs testbenches (it
    returns []); that is enforced here rather than in the backend so the
    error is raised consistently.
    """
    tb_sections = [n for n in manifest.section_order if n.startswith("tb:")]

    if tool == "vivado":
        if tb_arg:
            raise RunnerError("vivado synthesis does not accept --tb")
        return []

    if tb_arg is not None:
        if tb_arg == "all":
            if not tb_sections:
                raise RunnerError("--tb all but manifest has no testbench sections")
            return tb_sections
        name = f"tb:{tb_arg}"
        if name not in manifest.sections:
            raise RunnerError(f"testbench [{name}] not found in {manifest.path.name}")
        return [name]

    # No --tb: DEFAULT_TB, else single implicit, else error.
    if "DEFAULT_TB" in manifest.directives:
        default = f"tb:{manifest.directives['DEFAULT_TB']}"
        if default not in manifest.sections:
            raise RunnerError(f"DEFAULT_TB refers to missing [{default}]")
        return [default]
    if len(tb_sections) == 1:
        return tb_sections
    if not tb_sections:
        raise RunnerError("manifest has no testbench section")
    raise RunnerError("multiple testbenches; select one with --tb or set DEFAULT_TB")


def target_sections(manifest: Manifest, tb_name: str | None) -> list[str]:
    """Section list for the requested target, in compile order.

    Simulation: [rtl] (if present) + the selected [tb:<name>].
    Synthesis:  [rtl] (if present) + [top] (if present) + [constraints:*].
    The same manifest therefore serves both flows: the testbench sections
    are simply not included for synthesis, and [top]/[constraints:*] are
    not included for simulation.
    """
    sections = []
    if "rtl" in manifest.sections:
        sections.append("rtl")
    if tb_name is not None:
        sections.append(tb_name)
    else:
        if "top" in manifest.sections:
            sections.append("top")
        cons = [n for n in manifest.section_order if n.startswith("constraints:")]
        if cons:
            sections.extend(cons)
    return sections


