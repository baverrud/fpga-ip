#!/usr/bin/env python3
r"""run.py - fpga-ip manifest runner.

Resolves the selected .f manifest for an IP, filters the sources by the tool
profile from tool_capabilities.ini, and dispatches to an EDA backend. The
ModelSim/Questa backend writes a flat, reusable Tcl script into <ip>/scripts/
and launches vsim.

Running the axis_fifo VHDL simulation (ModelSim, GUI) -- three ways:

  1. Via this runner, from the fpga-ip repo root:
       run axis_fifo vhdl modelsim gui

  2. Directly from the IP scripts directory (script generated by method 1):
       cd axis_fifo/scripts
       vsim -do sim_vhdl_msim_default_gui.tcl

  3. Directly from the IP sim directory (same script, relative path):
       cd axis_fifo/sim
       vsim -do ..\scripts\sim_vhdl_msim_default_gui.tcl

Project mode creates a native ModelSim/Questa project (.mpf) in
<ip>/sim_proj/ and opens the GUI (the non-project <ip>/sim/ is untouched):

       run axis_fifo vhdl modelsim project

run.py copies the global %MODELSIM% ini to a writable local modelsim.ini in
<ip>/sim_proj/ and clears %MODELSIM% before launching vsim, so the .mpf can
be saved (see fpga-rules/questa_modelsim_project_guide.md).

Vivado XSim simulation (Vivado's built-in simulator), batch and GUI, builds
into <ip>/xsim/. run.py compiles (xvhdl/xvlog) and elaborates (xelab) - XSim
needs one VHDL standard per work library, so all VHDL is compiled at the
manifest DEFAULT_STD - then runs via a generated .tcl (batch) or the GUI:

       run axis_fifo vhdl xsim batch
       run axis_fifo vhdl xsim gui

Vivado synthesis: batch runs non-project synthesis headless in <ip>/vivado/;
gui loads the design in non-project mode and leaves the Vivado GUI open;
project creates a native .xpr project (design + testbench sources) in
<ip>/vivado_proj/ and opens the GUI:

       run axis_fifo vhdl vivado batch
       run axis_fifo vhdl vivado gui
       run axis_fifo vhdl vivado project

Remove build artifacts for an IP (deletes <ip>/sim/, <ip>/sim_proj/,
<ip>/xsim/, <ip>/vivado/, and <ip>/vivado_proj/):
       run clean <ip>

The generated script is self-locating: it derives the repo root from its own
launch directory and changes into <ip>/sim/ itself, so methods 2 and 3 need
no Python and keep all build artifacts under <ip>/sim/.

Spec: common/doc/run-py.md and common/doc/f-format.md
"""

