def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="run",
        description="fpga-ip manifest runner",
        epilog=(
            "examples:\n"
            "  run axis_fifo vhdl modelsim gui\n"
            "  run axis_fifo vhdl modelsim project\n"
            "  run axis_fifo vhdl modelsim --tb default\n"
            "  run axis_fifo vhdl xsim batch\n"
            "  run axis_fifo vhdl xsim gui\n"
            "  run axis_fifo vhdl vivado batch\n"
            "  run axis_fifo vhdl vivado gui\n"
            "  run axis_fifo vhdl vivado project\n"
            "  run clean axis_fifo"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument("ip", help="IP directory under the repo root")
    p.add_argument("manifest", help="manifest name (vhdl or vhdl.f)")
    p.add_argument("tool", help="tool profile name (modelsim, questa, vivado, xsim)")
    p.add_argument("--tb", dest="tb", default=None,
                   help="testbench name, or 'all'")
    p.add_argument("--part", default=None,
                   help=f"Vivado target part (default: {VIVADO_DEFAULT_PART})")
    p.add_argument("--version", default=None, help="optional tool version override")
    p.add_argument("--edition", default=None, help="optional tool edition override")
    p.add_argument("mode", nargs="?", default="batch",
                   help="batch (default), gui, or project")
    return p


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] == "clean":
        return cmd_clean(argv[1:])
    args = build_arg_parser().parse_args(argv)

    mode = args.mode
    if mode not in VALID_MODES:
        print(f"ERROR: unknown mode '{mode}' (expected {', '.join(VALID_MODES)})", file=sys.stderr)
        return 2

    try:
        caps = Capabilities.load(INI_PATH)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    tool = args.tool
    if not caps.has_tool(tool):
        print(f"ERROR: unsupported tool '{tool}' (no profile in tool_capabilities.ini)",
              file=sys.stderr)
        return 2
    modes = caps.profile_modes(tool)
    if modes and mode not in modes:
        print(f"ERROR: mode '{mode}' not supported by '{tool}' (modes: {', '.join(modes)})",
              file=sys.stderr)
        return 2

    manifest_name = args.manifest if args.manifest.endswith(".f") else args.manifest + ".f"
    manifest_path = (REPO_ROOT / args.ip / "scripts" / manifest_name).resolve()
    try:
        manifest_path.relative_to(REPO_ROOT)
    except ValueError:
        print(f"ERROR: manifest path escapes repo root: {manifest_path}", file=sys.stderr)
        return 2

    try:
        manifest = parse_manifest(manifest_path)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    try:
        tb_names = select_testbenches(manifest, args.tb, tool)
    except RunnerError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    provided = caps.effective_features(tool, args.version, args.edition)
    manifest_cache: dict[Path, Manifest] = {manifest.path: manifest}

    exit_code = 0
    for tb_name in tb_names or [None]:
        tb_label = tb_name.removeprefix("tb:") if tb_name else "synthesis"
        sections = target_sections(manifest, tb_name)
        try:
            files = build_closure(manifest, sections, tool, manifest_cache)
        except RunnerError as exc:
            print(f"ERROR: {exc}", file=sys.stderr)
            return 2

        # Header
        print(f"target   : {args.ip} / {manifest_name} / {tool} / {tb_label} / {mode}")
        if tb_name:
            meta = manifest.sections[tb_name].meta
            requires = parse_feature_tokens(meta.get("requires", ""))
            req_names = [n for _, n in requires]
            bad = [n for n in req_names if n not in caps.allowed]
            if bad:
                print(f"ERROR: requires token(s) not in allowed_features: {', '.join(bad)}",
                      file=sys.stderr)
                return 2
            print(f"top      : {meta.get('top', '(missing)')}")
            print(f"requires : {', '.join(req_names) if req_names else '(none)'}")
        print("files (compile order):")
        missing_paths: list[Path] = []
        for entry in files:
            rel = entry.path.relative_to(REPO_ROOT).as_posix()
            opts = entry.compile_options()
            if entry.path.is_file():
                print(f"  [OK   ] [{entry.section:12}] {opts:24} {GREEN}{rel}{RESET}")
            else:
                print(f"  [MISS ] [{entry.section:12}] {opts:24} {RED}{rel}{RESET}")
                missing_paths.append(entry.path)
        print()

        ok_count = len(files) - len(missing_paths)
        if missing_paths:
            summary = (f"{GREEN}{ok_count} found{RESET}, "
                       f"{RED}{len(missing_paths)} missing{RESET}")
        else:
            summary = f"{GREEN}{len(files)} files found{RESET}"
        print(f"  summary: {summary}")

        if missing_paths:
            for p in missing_paths:
                print(f"{RED}ERROR: source file not found: {p}{RESET}", file=sys.stderr)
            return 2

        if tb_name:
            meta = manifest.sections[tb_name].meta
            req_names = [n for _, n in parse_feature_tokens(meta.get("requires", ""))]
            missing = [n for n in req_names if n not in provided]
            if missing:
                print(f"  WARNING: missing capability(ies) for '{tool}': {', '.join(missing)}")
                exit_code = 3

        # ModelSim / Questa simulation backend (non-project mode).
        if tb_name is not None and tool in MSIM_TOOLS:
            top = manifest.sections[tb_name].meta.get("top")
            if not top:
                print(f"ERROR: testbench [{tb_name}] has no 'top' metadata", file=sys.stderr)
                return 2
            time_res = manifest.sections[tb_name].meta.get("time_res")
            manifest_base = manifest_name[:-2] if manifest_name.endswith(".f") else manifest_name
            # Filename segments follow the command-line order:
            #   run <ip> <manifest> <tool> [--tb <tb>] [mode]
            # -> sim_<manifest>_<tool>_<tb>_<mode>.tcl  (synthesis omits tb).
            # Shorten common tool names in the filename (modelsim -> msim).
            tool_tag = {"modelsim": "msim"}.get(tool, tool)
            if tb_name:
                script_name = f"sim_{manifest_base}_{tool_tag}_{tb_label}_{mode}.tcl"
            else:
                script_name = f"sim_{manifest_base}_{tool_tag}_{mode}.tcl"
            script_path = REPO_ROOT / args.ip / "scripts" / script_name
            write_msim_script(script_path, files, top, time_res, mode, tool,
                              manifest_base, args.ip, tb_label, script_name)
            print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            # The generated script self-cds into <ip>/sim/ and rebuilds the
            # work library itself, so nothing is cleaned here. Use
            # 'run clean <ip>' to remove the build artifacts under <ip>/sim/.
            rc = run_msim(script_path.parent, script_name, mode)
            exit_code = report_sim_result(mode, rc) or exit_code
        # Vivado XSim simulation backend (batch/gui; no project mode).
        elif tb_name is not None and tool == "xsim":
            # XSim ships no UVVM libraries; skip testbenches whose requires
            # the xsim profile does not provide (mirrors simulate_xsim.bat).
            meta = manifest.sections[tb_name].meta
            req_names = [n for n, _ in parse_feature_tokens(meta.get("requires", ""))]
            missing = [n for n in req_names if n not in provided]
            if missing:
                print(f"  SKIP: testbench [{tb_name}] requires capabilities not "
                      f"provided by 'xsim': {', '.join(missing)}")
                continue
            top = meta.get("top")
            if not top:
                print(f"ERROR: testbench [{tb_name}] has no 'top' metadata", file=sys.stderr)
                return 2
            manifest_base = manifest_name[:-2] if manifest_name.endswith(".f") else manifest_name
            script_name = f"sim_{manifest_base}_{tool}_{tb_label}_{mode}.tcl"
            script_path = REPO_ROOT / args.ip / "scripts" / script_name
            write_xsim_script(script_path, top, mode, tool,
                              manifest_base, args.ip, tb_label, script_name)
            print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            # XSim needs one VHDL standard per work library, so all VHDL is
            # compiled at the manifest default; flag mixed-std manifests.
            std = manifest.default_std()
            vhdl_stds = {e.std or std for e in files
                         if e.path.suffix.lower() in (".vhd", ".vhdl")}
            if len(vhdl_stds) > 1:
                print(f"  NOTE: XSim compiles all VHDL at DEFAULT_STD {std} "
                      f"(one standard per work library; per-file std ignored)")
            rc = run_xsim(script_path.parent, script_path, files, top, mode, std)
            exit_code = report_sim_result(mode, rc) or exit_code
        # Vivado synthesis backend (batch/gui/project).
        elif tool == "vivado":
            if "top" not in manifest.sections:
                print("ERROR: manifest has no [top] section; synthesis requires "
                      "a top-level wrapper", file=sys.stderr)
                return 2
            top = _top_entity(files)
            if not top:
                print("ERROR: cannot determine the top entity from the [top] "
                      "section", file=sys.stderr)
                return 2
            part = args.part or VIVADO_DEFAULT_PART
            manifest_base = manifest_name[:-2] if manifest_name.endswith(".f") else manifest_name
            script_name = f"synth_{manifest_base}_{tool}_{mode}.tcl"
            script_path = REPO_ROOT / args.ip / "scripts" / script_name
            if mode in ("batch", "gui"):
                # Non-project: batch runs headless, gui loads the design and
                # leaves the Vivado GUI open. No project, no testbenches.
                if mode == "batch":
                    write_vivado_synth_script(script_path, files, top, part, tool,
                                              manifest_base, args.ip, script_name)
                else:
                    write_vivado_gui_script(script_path, files, top, part, tool,
                                            manifest_base, args.ip, script_name)
                build_dir = REPO_ROOT / args.ip / "vivado"
                proj_dir = None
            else:
                # project: native .xpr with testbench sources in sim_1, then GUI.
                tb_sections = [n for n in manifest.section_order if n.startswith("tb:")]
                sim_files: list[FileEntry] = []
                if tb_sections:
                    try:
                        sim_files = [e for e in
                                     build_closure(manifest, tb_sections, tool, manifest_cache)
                                     if e.path.is_file()]
                    except RunnerError as exc:
                        print(f"ERROR: {exc}", file=sys.stderr)
                        return 2
                write_vivado_project_script(script_path, files, sim_files, top,
                                            part, mode, tool, manifest_base,
                                            args.ip, script_name)
                build_dir = REPO_ROOT / args.ip / "vivado_proj"
                proj_dir = build_dir / f"{top}_proj"
            print(f"script   : {script_path.relative_to(REPO_ROOT).as_posix()}")
            rc = run_vivado(build_dir, script_path, mode, proj_dir)
            exit_code = report_sim_result(mode, rc) or exit_code

    return exit_code


if __name__ == "__main__":
    sys.exit(main())
