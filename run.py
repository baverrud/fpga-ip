# Target part for IP-level synthesis (matches the legacy synth_vivado.tcl
# default). Override per-run with --part; board-level projects (e.g. ZCU104)
# pass their own part number.
VIVADO_DEFAULT_PART = "xc7a35tftg256-1"


def _vivado_read_lines(files: list[FileEntry], indent: str = "") -> list[str]:
    """Return the read_vhdl/read_verilog/read_xdc commands for a closure."""
    out: list[str] = []
    for e in files:
        rel = e.path.relative_to(REPO_ROOT).as_posix()
        if e.path.suffix.lower() == ".xdc":
            out.append(f'{indent}read_xdc "$repo_root/{rel}"')
        elif e.path.suffix.lower() in (".vhd", ".vhdl"):
            flag = {"1993": "", "2019": " -vhdl2019"}.get(e.std or "2008", " -vhdl2008")
            out.append(f'{indent}read_vhdl{flag} "$repo_root/{rel}"')
        else:
            out.append(f'{indent}read_verilog -sv "$repo_root/{rel}"')
    return out


def _vivado_file_type(entry: FileEntry) -> str:
    """Map a source entry to its Vivado file_type property value."""
    if entry.path.suffix.lower() == ".sv":
        return "SystemVerilog"
    return {"1993": "VHDL", "2019": "VHDL 2019"}.get(entry.std or "2008", "VHDL 2008")


def _top_entity(files: list[FileEntry]) -> str | None:
    """Extract the top synthesis entity from the [top] section files."""
    for e in files:
        if e.section != "top":
            continue
        text = e.path.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r"^\s*entity\s+(\w+)\s+is", text, re.MULTILINE)
        if m:
            return m.group(1)
    return None


def _wrap_catch_exit(body: list[str]) -> list[str]:
    """Wrap a script body so any error exits nonzero (never the Vivado% prompt)."""
    out = ["# Run the flow; on any error, report and exit nonzero so batch",
           "# mode never drops to the interactive Vivado% prompt.",
           "proc run_flow {} {",
           "  global repo_root"]
    for line in body:
        out.append(("  " + line) if line else "")
    out += ["}",
            "if {[catch {run_flow} err]} {",
            '  puts "ERROR: $err"',
            "  exit 1",
            "}",
            "exit 0"]
    return out


def _vivado_header(manifest_name: str, tool: str, mode: str, top: str,
                   run_cmd: str, ip: str, build_dir: str,
                   script_name: str) -> list[str]:
    """Shared self-locating header for the generated Vivado Tcl scripts."""
    launch_mode = "gui" if mode == "gui" else "batch"
    return ["# ============================================================================",
            "# Generated by run.py - do not edit",
            f"# Manifest: {manifest_name}.f  Tool: {tool}  Mode: {mode}  Top: {top}",
            "#",
            f"# Create (from the fpga-ip repo root): ",
            f"#      {run_cmd}",
            "#",
            "# Vivado is launched from <ip>/<build_dir>/; the script derives the",
            "# fpga-ip repo root from its launch directory (two levels up).",
            "#",
            "# Run (from the fpga-ip repo root), e.g.:",
            f"#      cd {ip}/{build_dir}",
            f"#      vivado -mode {launch_mode} -source ..\\scripts\\{script_name}",
            "# ============================================================================",
            "",
            "set repo_root [file normalize [file join [pwd] .. ..]]",
            "if {![file exists $repo_root/tool_capabilities.ini]} {",
            f'  puts "ERROR: run this script from <ip>/{build_dir}/"',
            "  exit 1",
            "}",
            ""]


def write_vivado_synth_script(script_path: Path, files: list[FileEntry],
                              top: str, part: str, tool: str,
                              manifest_name: str, ip: str,
                              script_name: str) -> None:
    """Generate a non-project Vivado batch synthesis Tcl script.

    Run headless from <ip>/vivado/ via `vivado -mode batch -source`. The
    script reads the design closure ([rtl], [top], constraints), runs
    synth_design, writes utilization/timing reports, and always exits.
    See fpga-rules/vivado_synthesis_guide.md.
    """
    run_cmd = f"run {ip} {manifest_name} {tool} batch"
    body = [f"# Non-project synthesis of '{top}' on '{part}'.",
            f"set_part {part}"]
    body += _vivado_read_lines(files)
    body += ["",
             f"synth_design -top {top} -part {part}",
             "",
             "report_utilization -file utilization.rpt",
             "report_timing -file timing.rpt"]
    lines = _vivado_header(manifest_name, tool, "batch", top, run_cmd, ip,
                           "vivado", script_name) + _wrap_catch_exit(body)
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_vivado_gui_script(script_path: Path, files: list[FileEntry],
                            top: str, part: str, tool: str,
                            manifest_name: str, ip: str,
                            script_name: str) -> None:
    """Generate a non-project Vivado GUI Tcl script.

    Loads the design (set_part + read sources + synth_design) and leaves the
    Vivado GUI open, launched via `vivado -mode gui -source`. The design is
    synthesized in-memory; no .xpr project is created.
    """
    run_cmd = f"run {ip} {manifest_name} {tool} gui"
    lines = _vivado_header(manifest_name, tool, "gui", top, run_cmd, ip,
                           "vivado", script_name)
    lines += [f"# Non-project GUI: load '{top}' on '{part}', synthesize, and",
              "# leave the Vivado GUI open for interactive work.",
              f"set_part {part}"]
    lines.extend(_vivado_read_lines(files))
    lines += ["",
              f"synth_design -top {top} -part {part}",
              "",
              "# Do NOT exit - the Vivado GUI must stay open."]
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_vivado_project_script(script_path: Path, files: list[FileEntry],
                                sim_files: list[FileEntry], top: str, part: str,
                                mode: str, tool: str, manifest_name: str,
                                ip: str, script_name: str) -> None:
    """Generate a native Vivado project creation Tcl script.

    Used by gui (project + open GUI) and project (headless). Design sources
    ([rtl], [top]) go to sources_1, constraints to constrs_1, and testbench
    sources ([tb:*]) to sim_1, so the project is ready for both synthesis
    and simulation. See fpga-rules/vivado_synthesis_guide.md.
    """
    proj_name = f"{top}_proj"
    run_cmd = f"run {ip} {manifest_name} {tool} {mode}"
    lines = _vivado_header(manifest_name, tool, mode, top, run_cmd, ip,
                           "vivado_proj", script_name)
    body = [f"# Create the native Vivado project '{proj_name}' on '{part}'.",
            f"create_project -force {proj_name} ./{proj_name} -part {part}",
            "",
            "# Design sources ([rtl], [top]) into sources_1."]
    for e in files:
        if e.path.suffix.lower() == ".xdc":
            continue  # constraints handled below
        rel = e.path.relative_to(REPO_ROOT).as_posix()
        body.append(f'set f [add_files -norecurse -fileset sources_1 "$repo_root/{rel}"]')
        body.append(f'set_property file_type "{_vivado_file_type(e)}" $f')
    xdcs = [e for e in files if e.path.suffix.lower() == ".xdc"]
    if xdcs:
        body += ["",
                 "# Constraints ([constraints:*]) into constrs_1.",
                 'set cf [get_filesets -quiet constrs_1]',
                 'if {$cf eq ""} { set cf [create_fileset -constrset constrs_1] }']
        for e in xdcs:
            rel = e.path.relative_to(REPO_ROOT).as_posix()
            body.append(f'add_files -norecurse -fileset constrs_1 "$repo_root/{rel}"')
    if sim_files:
        body += ["",
                 "# Simulation sources ([tb:*]) into sim_1 (testbenches).",
                 'set sf [get_filesets -quiet sim_1]',
                 'if {$sf eq ""} { set sf [create_fileset -simset sim_1] }']
        for e in sim_files:
            rel = e.path.relative_to(REPO_ROOT).as_posix()
            body.append(f'set f [add_files -norecurse -fileset sim_1 "$repo_root/{rel}"]')
            body.append(f'set_property file_type "{_vivado_file_type(e)}" $f')
    body += ["",
             f"set_property top {top} [get_filesets sources_1]",
             "# Save the project to disk.",
             "close_project"]
    lines += _wrap_catch_exit(body)
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def run_vivado(build_dir: Path, script_path: Path, mode: str,
               proj_dir: Path | None) -> int:
    """Run the Vivado synthesis/project flow from a dedicated build dir.

    batch:   non-project synthesis, headless (vivado -mode batch).
    gui:     non-project GUI - the script loads the design and the Vivado
             GUI stays open (vivado -mode gui -source).
    project: creates the native .xpr project, then opens it in the GUI.

    The build directory is reset (removed + recreated) first. vivado must be
    on the PATH (Vivado env initialized via v23/v25/v26 in the caller's CMD
    shell); no machine-specific paths are referenced.
    """
    shutil.rmtree(build_dir, ignore_errors=True)
    build_dir.mkdir(parents=True, exist_ok=True)
    if mode == "gui":
        # Non-project GUI: -mode gui runs the script and keeps the GUI open.
        cmd = f"vivado -mode gui -source {script_path.as_posix()}"
        print(f"cmd : cmd.exe /c \"{cmd}\" (cwd: {build_dir})")
        return subprocess.run(["cmd.exe", "/c", cmd], cwd=build_dir).returncode
    # batch / project: run headless first (synthesis or project creation).
    cmd = f"vivado -mode batch -source {script_path.as_posix()}"
    print(f"cmd : cmd.exe /c \"{cmd}\" (cwd: {build_dir})")
    rc = subprocess.run(["cmd.exe", "/c", cmd], cwd=build_dir).returncode
    if rc != 0 or mode == "batch":
        return rc
    # project: open the created .xpr in the Vivado GUI (blocks until closed).
    if proj_dir is not None:
        xpr = proj_dir / f"{proj_dir.name}.xpr"
        if not xpr.is_file():
            print(f"ERROR: project file not found: {xpr}", file=sys.stderr)
            return 1
        cmd = f"vivado {xpr.as_posix()}"
        print(f"cmd : cmd.exe /c \"{cmd}\" (cwd: {build_dir})")
        return subprocess.run(["cmd.exe", "/c", cmd], cwd=build_dir).returncode
    return 0


def report_sim_result(mode: str, rc: int) -> int:
    """Print the result line for a target; return exit-code delta.

    Batch mode maps rc to PASS (0) / FAIL (nonzero). GUI/project modes report
    that the GUI was launched and never fail the run.
    """
    if mode == "batch":
        if rc == 0:
            print(f"{GREEN}result   : PASS{RESET}")
            return 0
        print(f"{RED}result   : FAIL (exit {rc}){RESET}")
        return 1
    print("result   : GUI launched")
    return 0


def cmd_clean(argv: list[str]) -> int:
    """Subcommand: remove build artifacts for an IP.

    Usage: run.py clean <ip>

    Deletes <ip>/sim/ (non-project build: work library, transcripts, wave
    logs), <ip>/sim_proj/ (project-mode build: the same plus the .mpf
    project), <ip>/xsim/ (XSim build: xsim.dir and logs), <ip>/vivado/
    (batch synthesis), and <ip>/vivado_proj/ (Vivado project mode). A
    directory held open by a running tool is reported and left in place.
    """
    p = argparse.ArgumentParser(
        prog="run clean",
        description="Remove an IP's build artifacts (sim/, sim_proj/, xsim/, vivado/, vivado_proj/)",
    )
    p.add_argument("ip", help="IP directory under the repo root")
    args = p.parse_args(argv)

    removed = []
    for name in ("sim", "sim_proj", "xsim", "vivado", "vivado_proj"):
        build_dir = REPO_ROOT / args.ip / name
        if not build_dir.exists():
            continue
        try:
            shutil.rmtree(build_dir)
        except PermissionError:
            print(f"ERROR: build directory is locked by a running tool "
                  f"({build_dir}); close the tool and retry.", file=sys.stderr)
            return 2
        removed.append(build_dir.relative_to(REPO_ROOT).as_posix())
    if not removed:
        print(f"nothing to clean: no build dirs under {args.ip}/")
        return 0
    print("removed build artifacts: " + ", ".join(removed))
    return 0


